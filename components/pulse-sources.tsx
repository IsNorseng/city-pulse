"use client";

import {Tabs, TabsList, TabsTrigger, TabsContent} from '@/components/ui/tabs';
import {observations, type Observation} from '@/lib/real-data';
import {money} from '@/lib/pulse-data';

function description(record: Observation) {
  if (record.id === 'rent1' || record.id === 'rent2') {
    return 'Средняя ставка долгосрочной аренды в объявлениях. Элитные квартиры исключены из выборки.';
  }
  if (record.id === 'sqm') {
    return 'Средняя цена предложения на вторичном рынке за один квадратный метр.';
  }
  return 'Средняя стоимость однокомнатной квартиры на вторичном рынке. ЦИАН не уточняет, использованы цены объявлений или сделок.';
}

function changeDescription(change: number | null) {
  if (change === null) return 'Изменение для города не указано';
  if (change === 0) return 'За год: 0% по данным источника';
  return `На ${money(Math.abs(change), 1)}% ${change > 0 ? 'выше' : 'ниже'}, чем годом ранее`;
}

export function SourceContent() {
  return <div className="sheet-body">
    <Tabs defaultValue="sources">
      <TabsList className="source-tabs">
        <TabsTrigger value="sources">Источники</TabsTrigger>
        <TabsTrigger value="method">Как считать</TabsTrigger>
      </TabsList>

      <TabsContent value="sources">
        <p>Восемь показателей из трёх публикаций ЦИАН проверены 4 октября 2026 года. В этом выпуске сохранены именно эти значения.</p>
        {Object.entries(observations).map(([cityKey, records]) => <section key={cityKey}>
          <h2 className="mt-7 text-lg">{records[0]?.city}</h2>
          {records.map(record => <article className="publication-card" key={`${cityKey}-${record.id}`}>
            <span className="panel-tag">{record.period}</span>
            <h3>{record.label}</h3>
            <div className="publication-value">{money(record.value)} <span>{record.unit}</span></div>
            <p>{changeDescription(record.change)}</p>
            <p>{description(record)}</p>
            <dl>
              <div><dt>Где</dt><dd>{record.geo}</dd></div>
              <div><dt>Публикация</dt><dd>{record.published}</dd></div>
            </dl>
            <a href={record.url} target="_blank" rel="noreferrer">{record.source} · таблица по городам ↗</a>
          </article>)}
        </section>)}
      </TabsContent>

      <TabsContent value="method">
        <h3>Что означают числа</h3>
        <p>ЦИАН публикует средние значения. Они описывают рынок и могут отличаться от цены конкретной квартиры. Медиана и средняя — разные показатели; здесь приведена средняя.</p>

        <h3>Как читать периоды</h3>
        <p>Аренда и цена квадратного метра относятся к сентябрю 2026 года, стоимость однокомнатной квартиры — к январю 2026 года. Это разные срезы. Месяц в публикации не означает среднее за полный календарный месяц; точный день замера не установлен.</p>
        <p>Источники проверены 4 октября 2026 года. Дата проверки и дата публикации показываются отдельно от периода, к которому относится число.</p>

        <h3>Цены жилья</h3>
        <p>Аренда — ставки в объявлениях, квадратный метр — цена предложения на вторичном рынке. Для средней стоимости однокомнатной квартиры источник не уточняет, взяты цены объявлений или сделок.</p>
        <p>В заголовке исходной таблицы цены квадратного метра ошибочно добавлено «в месяц». Название показателя и текст статьи описывают цену покупки за м², поэтому здесь используется ₽/м². К единице аренды это уточнение не относится.</p>

        <h3>Ваш бюджет</h3>
        <p>Укажите свой доход и расходы на ЖКХ, продукты, транспорт и связь. Аренда по умолчанию взята из средней городской ставки однокомнатной квартиры; её можно заменить своей суммой. Пока обязательные поля не заполнены, остаток не рассчитывается. Нулевой расход нужно указать явно.</p>
        <p><strong>Остаток = доход на руки − аренда − ЖКХ − продукты − транспорт − связь.</strong> Отрицательный остаток показывает, сколько не хватает на выбранные расходы. Это ваш расчёт, а не доход типичного жителя города.</p>

        <h3>До налога и на руки</h3>
        <p>Если доход указан «На руки», налог повторно не вычитается. Для дохода «До налога» расчёт предполагает одинаковую зарплату каждый месяц, налоговое резидентство РФ, отсутствие вычетов и других доходов.</p>
        <details>
          <summary className="cursor-pointer text-sm text-[#3855d3]">Годовая шкала НДФЛ</summary>
          <p>На первые 2,4 млн ₽ годового дохода применяется 13%; на часть от 2,4 до 5 млн ₽ — 15%; от 5 до 20 млн ₽ — 18%; от 20 до 50 млн ₽ — 20%; свыше 50 млн ₽ — 22%. Повышенная ставка применяется только к части дохода выше порога.</p>
          <p>Годовой доход после налога делится на 12. Фактическая сумма на руки в отдельном месяце может отличаться.</p>
          <a href="https://www.nalog.gov.ru/rn78/news/activities_fts/15766617/" target="_blank" rel="noreferrer">ФНС · шкала НДФЛ с 2025 года ↗</a>
        </details>

        <h3>Доступность покупки</h3>
        <p>Цена квартиры делится на ваш годовой доход на руки, а годовой доход — на цену квадратного метра. Результат показывает соотношение цены и дохода. Он не учитывает ваши расходы и не означает срок накопления. Цена квартиры и цена м² относятся к разным месяцам.</p>
        <p>Введённые суммы остаются в вашем браузере и не отправляются на внешний сервер.</p>
      </TabsContent>
    </Tabs>
  </div>;
}
